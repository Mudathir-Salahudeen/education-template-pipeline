"""Update existing templates: add a new year of data entry and pre-fill known values.

Adding a year is done *in place* on a country's own workbook, so every value it
already reported is kept. Formulas for the new column are generated by shifting the
previous year's formulas (openpyxl's Translator), so any formula in the template,
not just the ones this project created, is carried forward correctly.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from openpyxl import load_workbook
from openpyxl.formula.translate import Translator
from openpyxl.utils import get_column_letter

from . import config as C
from .template import _add_validation, row_of, sheet_rows, style_year_column, year_columns


def add_year(wb, new_year: int) -> list[str]:
    """Append a column for `new_year` to every data and indicator sheet. Returns a change log."""
    log = []
    for sheet in C.DATA_SHEETS + ["Indicators"]:
        ws = wb[sheet]
        cols = year_columns(ws)
        if new_year in cols:
            log.append(f"{sheet}: {new_year} already present, skipped")
            continue
        last_year = max(cols)
        if new_year != last_year + 1:
            raise ValueError(f"{sheet}: can only add {last_year + 1}, not {new_year}")
        prev_col, new_col = cols[last_year], cols[last_year] + 1
        ws.cell(C.HEADER_ROW, new_col, new_year)
        style_year_column(ws, sheet, new_col)
        # Carry forward whatever formula the previous year had (shifted one column)
        n_formulas = 0
        for key in sheet_rows(sheet):
            r = row_of(sheet, key)
            prev = ws.cell(r, prev_col).value
            if isinstance(prev, str) and prev.startswith("="):
                origin = f"{get_column_letter(prev_col)}{r}"
                target = f"{get_column_letter(new_col)}{r}"
                ws.cell(r, new_col).value = Translator(prev, origin=origin).translate_formula(target)
                n_formulas += 1
        if sheet in C.DATA_SHEETS:
            _add_validation(ws, sheet, new_col, new_col)
        log.append(f"{sheet}: added {new_year} (column {get_column_letter(new_col)}), {n_formulas} formulas carried forward")
    return log


def prefill(wb, rows: pd.DataFrame) -> int:
    """Write known values (e.g. population projections) into empty input cells.

    rows: columns sheet, level, sex, age, year, value. Never overwrites a value
    the country has already entered. Returns the number of cells filled.
    """
    filled = 0
    for sheet, grp in rows.groupby("sheet"):
        ws = wb[sheet]
        cols = year_columns(ws)
        keys = set(sheet_rows(sheet))
        for rec in grp.itertuples(index=False):
            age = int(rec.age) if str(rec.age).isdigit() else rec.age
            key = (rec.level, rec.sex, age)
            if key not in keys or int(rec.year) not in cols:
                continue
            cell = ws.cell(row_of(sheet, key), cols[int(rec.year)])
            if cell.value in (None, ""):
                cell.value = int(rec.value)
                filled += 1
    return filled


def update_folder(src: Path, dst: Path, new_year: int, prefill_csv: Path | None = None) -> list[str]:
    dst.mkdir(parents=True, exist_ok=True)
    prefill_df = pd.read_csv(prefill_csv) if prefill_csv else None
    log = []
    for path in sorted(src.glob("*.xlsx")):
        wb = load_workbook(path)
        iso = wb["Info"].cell(C.HEADER_ROW + C.INFO_FIELDS.index("ISO code"), 2).value
        for line in add_year(wb, new_year):
            log.append(f"{path.name} | {line}")
        if prefill_df is not None:
            n = prefill(wb, prefill_df[prefill_df["iso"] == iso])
            log.append(f"{path.name} | pre-filled {n} cells")
        wb.save(dst / path.name)
    return log
